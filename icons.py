_HEAD = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">'


def _fp(d: str, c: str = "FG") -> str:
    """مسیرِ توپُر (لایه‌ی پر)"""
    return f'<path d="{d}" fill="@{c}@" stroke="none"/>'


def _sp(d: str, w: float = 2.0, c: str = "FG") -> str:
    """مسیرِ خطی پررنگ با سرِ گرد"""
    return (f'<path d="{d}" fill="none" stroke="@{c}@" stroke-width="{w}" '
            'stroke-linecap="round" stroke-linejoin="round"/>')


def _fc(cx: float, cy: float, r: float, c: str = "FG") -> str:
    """دایره‌ی توپُر"""
    return f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="@{c}@" stroke="none"/>'


def _sc(cx: float, cy: float, r: float, w: float = 2.0, c: str = "FG") -> str:
    """حلقه‌ی خطی"""
    return (f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" '
            f'stroke="@{c}@" stroke-width="{w}"/>')


def _fr(x, y, w, h, rx, c: str = "FG") -> str:
    """مستطیل گردِ توپُر"""
    return (f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" '
            f'fill="@{c}@" stroke="none"/>')


def _sr(x, y, w, h, rx, sw: float = 2.0, c: str = "FG") -> str:
    """مستطیل گردِ خطی"""
    return (f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" '
            f'fill="none" stroke="@{c}@" stroke-width="{sw}"/>')


def _g(*parts: str) -> str:
    """گروه با چرخش — برای گلیف‌های مورب (مثل راکت)"""
    body = "".join(parts)
    return (f'<g transform="rotate(40 12 12)">{body}</g>')


def _svg(*layers: str) -> str:
    return _HEAD + "".join(layers) + "</svg>"




def _parse_color(css: str):
    """'#hex' یا 'rgba(r,g,b,a)' → (hex6, opacity ۰..۱) — سازگار با QtSvg"""
    s = (css or "").strip()
    try:
        if s.startswith("rgba"):
            inner = s[s.index("(") + 1:s.rindex(")")]
            parts = [v.strip() for v in inner.split(",")]
            r, g, b = int(parts[0]), int(parts[1]), int(parts[2])
            a = float(parts[3])
            a = a if a <= 1.0 else a / 255.0
            return f"#{r:02X}{g:02X}{b:02X}", max(0.0, min(1.0, a))
        c = s if s.startswith("#") else {"none": None}.get(s, s)
        if s.lower() == "none":
            return None, 1.0
        if s.startswith("#"):
            if len(s) == 9:  # #AARRGGBB → تبدیل
                a = int(s[1:3], 16) / 255.0
                return "#" + s[3:], a
            return s[:7], 1.0
        return "#FFFFFF", 1.0
    except Exception:
        return "#FFFFFF", 1.0


def _attr(token: str, base: str, css: str) -> str:
    """'fill=\"@FG@\"' را با رنگ + opacity سازگار QtSvg جایگزین می‌کند"""
    hexc, op = _parse_color(css)
    if hexc is None:
        return f'{base}="none"'
    if op >= 0.999:
        return f'{base}="{hexc}"'
    return f'{base}="{hexc}" {base}-opacity="{op:.3f}"'


def svg_bytes(kind: str, fg: str, soft: str) -> QByteArray:
    """قالب SVG را با رنگ‌های داده‌شده پر می‌کند؛
    رنگ‌های نیمه‌شفاف با fill-opacity/stroke-opacity تزریق می‌شوند
    (QtSvg مقدار rgba() را در ویژگی‌ها نمی‌فهمد و سیاه رندر می‌کند).
    v6: گلیف‌ها دو لایه دارند — @SOFT@ (بدنه‌ی نرم) و @FG@ (تمرکزِ توپُر)."""
    raw = _SVGS.get(kind)
    if raw is None:
        raw = _SVGS["spark"]
    for token, css in (("@FG@", fg), ("@SOFT@", soft)):
        raw = raw.replace(f'fill="{token}"', _attr(token, "fill", css))
        raw = raw.replace(f'stroke="{token}"', _attr(token, "stroke", css))
        raw = raw.replace(token, "#FFFFFF")
    return QByteArray(raw.encode("utf-8"))


def _paint_lang_glyphs(p: "QPainter", size: int, fg: str):
    """آیکون FA/EN — الگوی دودوتونِ آیکون ترجمه (هم‌خانواده‌ی گلیف‌های v6):
    • حباب بالا: توپرِ نیمه‌شفافِ اکسنت + خطِ دورِ اکسنت — گلیف «فا» روی آن
    • حباب پایین: توپرِ کاملِ اکسنت با «EN» سفید — مثل متنِ روی دکمه‌ی اکسنت
    حباب‌ها/دم‌ها با QPainter کشیده می‌شوند (QtSvg تگ <text> ندارد)؛
    فونت‌ها: وزیرمتن برای «فا»، اسپیس‌گروتسک برای «EN» — باندل‌شده؛
    در نبودشان فونت پیش‌فرض سیستم می‌نشیند و شکل حفظ است."""
    s = size / 24.0
    col = QColor(fg)
    p.setRenderHint(QPainter.RenderHint.TextAntialiasing, True)

    top = QRectF(1.9 * s, 2.3 * s, 13.2 * s, 9.4 * s)
    bot = QRectF(8.9 * s, 12.3 * s, 13.2 * s, 9.4 * s)
    rad = 3.2 * s
    align = int(Qt.AlignmentFlag.AlignHCenter | Qt.AlignmentFlag.AlignVCenter)

    # دمِ حباب بالا (پایین-چپ) و دمِ حباب پایین (بالا-راست)
    p.setPen(Qt.NoPen)
    p.setBrush(col)
    p.drawPolygon(QPolygonF([
        QPointF(4.2 * s, 11.6 * s), QPointF(3.2 * s, 14.4 * s),
        QPointF(6.4 * s, 11.7 * s)]))
    p.drawPolygon(QPolygonF([
        QPointF(19.8 * s, 12.4 * s), QPointF(20.8 * s, 9.6 * s),
        QPointF(17.6 * s, 12.3 * s)]))

    # حباب بالا — لایه‌ی نرم (توپرِ کم‌رنگ) + لبه‌ی اکسنت؛ هم‌ساختار دودوتون
    soft_col = QColor(col)
    soft_col.setAlpha(52)
    p.setBrush(soft_col)
    p.drawRoundedRect(top, rad, rad)
    pen = QPen(col, 1.8 * s)
    pen.setCapStyle(Qt.PenCapStyle.RoundCap)
    pen.setJoinStyle(Qt.PenJoinStyle.RoundJoin)
    p.setPen(pen)
    p.setBrush(Qt.NoBrush)
    p.drawRoundedRect(top, rad, rad)

    # حباب پایین — توپرِ کامل
    p.setPen(Qt.NoPen)
    p.setBrush(col)
    p.drawRoundedRect(bot, rad, rad)

    # گلیف «فا» — رنگ اکسنت روی لایه‌ی نرم
    f_fa = QFont("Vazirmatn")
    f_fa.setPixelSize(max(4, round(6.9 * s)))
    f_fa.setBold(True)
    p.setFont(f_fa)
    p.setPen(col)
    p.drawText(top, align, "فا")

    # گلیف «EN» — سفید روی توپر (مثل on_accent)
    f_en = QFont("Space Grotesk")
    f_en.setPixelSize(max(4, round(6.4 * s)))
    f_en.setBold(True)
    p.setFont(f_en)
    p.setPen(QColor("#ffffff"))
    p.drawText(bot, align, "EN")


def icon_pixmap(kind: str, size: int, fg: str, soft: str) -> "QImage":
    """آیکون SVG را در اندازه‌ی دلخواه رندر می‌کند (QImage شفاف)؛
    آیکون faen بعد از SVG، گلیف‌های متنی هم می‌گیرد"""
    img = QImage(size, size, QImage.Format.Format_ARGB32)
    img.fill(Qt.GlobalColor.transparent)
    r = QSvgRenderer(svg_bytes(kind, fg, soft))
    p = QPainter(img)
    p.setRenderHint(QPainter.Antialiasing)
    r.render(p, QRectF(0, 0, size, size))
    if kind == "faen":
        _paint_lang_glyphs(p, size, fg)
    p.end()
    return img


def icon_qicon(kind: str, size: int, fg: str, soft: str) -> "QIcon":
    """همان آیکون به‌صورت QIcon برای دکمه‌ها"""
    from PySide6.QtGui import QIcon, QPixmap
    return QIcon(QPixmap.fromImage(icon_pixmap(kind, size, fg, soft)))


